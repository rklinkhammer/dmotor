#!/usr/bin/env python3
"""Generate shared PS/ESP32 IDs and lengths from wire.json."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
schema = json.loads((Path(__file__).parent / 'wire.json').read_text())
lines = ['// Generated by software/protocol/monitor/generate.py; do not edit.',
         '#pragma once', '#include <cstddef>', '#include <cstdint>',
         'namespace dmotor_sw { namespace monitor {',
         f'constexpr uint8_t version={schema["version"]};',
         f'constexpr std::size_t max_payload={schema["max_payload"]}, max_decoded=33+max_payload, max_encoded=2*max_decoded+2;']
for enum, values in [('Type', {m['name']: m['id'] for m in schema['messages']}),
                     ('State', schema['states']), ('Nak', schema['nak_reasons'])]:
    base = 'uint16_t' if enum == 'Nak' else 'uint8_t'
    lines.append(f'enum class {enum} : {base} {{ ' + ', '.join(f'{k}={v}' for k, v in values.items()) + ' };')
lines += [f'constexpr uint32_t cleanup_flags={sum(schema["cleanup_flags"].values())};',
          'inline std::size_t payload_size(Type type) {', '    switch(type) {']
for message in schema['messages']:
    lines.append(f'    case Type::{message["name"]}:return {message["length"]};')
lines += ['    }', '    return max_payload+1;', '}', '} }', '']
text = '\n'.join(lines)
path = root / 'include/dmotor_sw/monitor_wire.hpp'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not path.exists() or path.read_text() != text:
        raise SystemExit('Monitor wire header is stale; run generate.py')
else:
    path.write_text(text)
