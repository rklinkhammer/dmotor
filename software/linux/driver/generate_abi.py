#!/usr/bin/env python3
"""Generate C controller offsets for the kernel backend from the shared schema."""
import json,sys
from pathlib import Path
root=Path(__file__).resolve().parents[3]
schema=json.loads((root/'abi/controller.json').read_text())
text='/* Generated by software/linux/driver/generate_abi.py. */\n#ifndef DMOTOR_KERNEL_REGS_H\n#define DMOTOR_KERNEL_REGS_H\n'
text+=f'#define DM_PROFILE {schema["identity"]}U\n'
for key,value in schema['registers'].items(): text+=f'#define DM_{key} {value}U\n'
text+='#endif\n'
p=Path(__file__).with_name('dmotor_regs.h')
if '--check' in sys.argv:
    if p.read_text()!=text: raise SystemExit('Stale kernel ABI header')
else: p.write_text(text)
